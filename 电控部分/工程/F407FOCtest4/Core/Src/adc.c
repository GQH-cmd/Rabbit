float32_t R_ntc_to_temperature(float32_t R_ntc, float32_t T_start, float32_t T_end, float32_t delta_T)
{
    static const float32_t NTCTAB[61] =
	{
		27.219, 25.641, 24.184, 22.834, 22.021, 21.581, 20.872, 19.786, 18.760, 17.926,
		17.792, 17.035, 16.181, 15.361, 14.674, 14.575, 13.968, 13.287, 12.631, 12.081,
		11.999, 11.481, 10.899, 10.336, 10.000, 9.790, 9.481, 8.976, 8.486, 8.011, 7.315,
		7.872, 7.440, 7.020, 6.948, 6.612, 6.566, 6.192, 5.827, 5.834, 5.501,
		5.472, 5.176, 4.917, 4.859, 4.550, 4.627, 4.344, 4.068, 4.161, 3.912,
		3.799, 3.668, 3.535, 3.429, 3.326, 3.196, 3.121, 3.014, 2.921, 2.726
	};
	const int size = 61;

    if (R_ntc > NTCTAB[0]) 
	{
		return T_start;
	}
//	printf("%.3f, %.3f\n", R_ntc,  NTCTAB[0]);
	
    if (R_ntc < NTCTAB[size-1]) return T_end;

    int low = 0, high = size - 1;
    while (low <= high)
	{
        int mid = (low + high) / 2;
        if (NTCTAB[mid] == R_ntc)
		{
            return T_start + mid * delta_T;
        } else if (NTCTAB[mid] > R_ntc)
		{
            low = mid + 1;
        } else
		{
            high = mid - 1;
        }
    }
//	printf("%.3f\n", R_ntc);

    int i = high;
    float32_t R_high = NTCTAB[i];
    float32_t R_low = NTCTAB[i+1];
    float32_t fraction = (R_high - R_ntc) / (R_high - R_low);
//	printf("%.3f\n", T_start + (i + fraction) * delta_T);
    
    return T_start + (i + fraction) * delta_T;
}

/* 读取ADC */
uint16_t Read_ADC_Value(ADC_HandleTypeDef* hadc, uint32_t channel)
{
	uint16_t adc_value = 0;
	ADC_ChannelConfTypeDef sConfig;
	sConfig.Channel = channel;
	HAL_ADC_ConfigChannel(hadc, &sConfig);

	HAL_ADC_Start(hadc);  // 启动ADC
	if (HAL_ADC_PollForConversion(hadc, HAL_MAX_DELAY) == HAL_OK)
	{  
		adc_value = HAL_ADC_GetValue(hadc);
	}
	//	HAL_ADC_Stop(hadc);  // 停止ADC

	return adc_value;
}
